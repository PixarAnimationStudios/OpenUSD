# Regenerates the images used by splines.md.
#
# This script may be run from any directory; the path below is relative to the
# ts library directory:
#
#     python script/genDocImages.py
#
# The python interpreter that runs this script is also used to run docGraph.py,
# so it must be one that can import pxr.
#
# Each command is preceded by a comment naming the section of splines.md that
# uses the image.  Cases for docGraph.py are defined in script/docGraph.py; use
# "docGraph.py --list" to see them.  Images of Museum splines use
# script/museumGraph.py instead.

import os
import subprocess
import sys

# Verify that we can import pxr.Ts before we generate a more cryptic error
# message from the docGraph.py
try:
    from pxr import Ts
except ImportError as exc:
    sys.exit(f'ImportError: {exc}: Cannot generate images.')

# The ts library directory, which contains script/ and doxygen/.
TS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCGRAPH = os.path.join(TS_DIR, "script", "docGraph.py")
MUSEUMGRAPH = os.path.join(TS_DIR, "script", "museumGraph.py")
IMAGES = os.path.join(TS_DIR, "doxygen", "images")

# These images are all referenced in splines.md and generaged by docGraph.py
# (docGraph.py case name, output image file name), in order.
DOC_CASES = [
    # Introduction: the worked example.
    ("IntroExample", "introExample.png"),

    # Features, interpolation modes.
    ("InterpModes", "interpModes.png"),

    # Features, dual-valued knots.
    ("DualValued", "dualValued.png"),

    # Features, extrapolation.
    ("ExtrapLinear", "extrapLinear.png"),
    ("ExtrapSloped", "extrapSloped.png"),
    ("LoopRepeat", "loopRepeat.png"),
    ("LoopReset", "loopReset.png"),
    ("LoopOscillate", "loopOscillate.png"),
    ("LoopBoundary", "loopBoundary.png"),

    # Features, tangent algorithms.
    ("AutoEase", "autoEase.png"),
]

# These images are referenced in regression.md and generated by museumGraph.py
# (museumGraph.py case name, output image file name, opts), in order.
MUSEUM_CASES = [
    # Regressive Splines in USD: example
    ("RegressiveS", "regressiveS.png", ['--no-title']),

    # When Regression Arises
    ("NearCenterVertical", "nearVertical.png", ['--title', 'Near vertical']),
    ("CenterVertical", "centerVertical.png", ['--title', 'Vertical']),
    ("RegressiveSStandard", "regressiveSStandard.png", ['--title', 'Regressive']),
    ("BoldS", "boldS.png", ['--no-title']),
    ("OneThirdFourThird", "oneThirdFourThird.png", ['--no-title']),
    ("FourThirdOneThird", "fourThirdOneThird.png", ['--no-title']),
    ("StartVert", "startVert.png", ['--no-title']),
    ("EndVert", "endVert.png", ['--no-title']),

    # Anti-Regression Strategies
    ("RegressiveS", "keepStart.png", ['--no-title', '--maya']),
    ("RegressiveS", "keepRatio.png", ['--no-title', '--keepRatio']),
]

def main():
    for case, image in DOC_CASES:
        cmd = [sys.executable, DOCGRAPH, case,
               "--out", os.path.join(IMAGES, image)]
        print(" ".join(cmd), flush=True)

        # Stop at the first failure.
        subprocess.run(cmd, check=True)

    for case, image, opts in MUSEUM_CASES:
        cmd = [sys.executable, MUSEUMGRAPH, case,
               "--width", "300",
               "--height", "300",
               "--bez",
               "--out", os.path.join(IMAGES, image)] + opts
        print(" ".join(cmd), flush=True)

        # Stop at the first failure.
        subprocess.run(cmd, check=True)

if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as exc:
        print('Failed to execute: ', ' '.join(exc.cmd), file=sys.stderr)
        sys.exit(exc.returncode)
