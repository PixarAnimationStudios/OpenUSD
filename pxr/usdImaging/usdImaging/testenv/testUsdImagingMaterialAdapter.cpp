// Helper class that stores dirtied prim entries
class DirtyNoticeListener : public HdSceneIndexObserver
{
public:
    void PrimsDirtied(
            const HdSceneIndexBase& sender,
            const DirtiedPrimEntries& entries) override {

        static const bool debugPrimsDirtied = false;
        if (debugPrimsDirtied) {
            for (const auto& entry : entries) {
                fprintf(stderr, "Prim dirty: %s\n", entry.primPath.GetText());
                fprintf(stderr, "Locators:\n\t");
                for (const auto& loc : entry.dirtyLocators) {
                    fprintf(stderr, "%s\n\t", loc.GetString().c_str());
                }
                fprintf(stderr, "\n");
            }
        }
        _dirtied.insert(_dirtied.end(), entries.cbegin(), entries.cend());
    }

    void PrimsAdded(
        const HdSceneIndexBase& sender,
        const AddedPrimEntries &entries) override {
        // Do nothing
    }

    void PrimsRemoved(
        const HdSceneIndexBase &sender,
        const RemovedPrimEntries &entries) override {
        // Do nothing
    };

    void PrimsRenamed(
        const HdSceneIndexBase &sender,
        const RenamedPrimEntries &entries) override {
        // Do nothing
    }

    DirtiedPrimEntries const& GetDirtied() { return _dirtied; }

    void ResetEntries() {
        _dirtied.clear();
    }

private:
    DirtiedPrimEntries _dirtied;
};

// Returns true if the \p dirtyLocators provided contain an entry that
// dirties the surface terminal.
// Returns false otherwise.
static bool
_CheckSurfaceTerminal(
    const HdDataSourceLocatorSet& dirtyLocators)
{
    return dirtyLocators.Contains({
        HdMaterialSchema::GetSchemaToken(), 
        _tokens->renderContext,
        HdMaterialSchemaTokens->terminals,
        _tokens->surface});
}

// Returns true if the \p dirtyLocators provided contain an entry that
// dirties \p shaderName for the given \p renderContext.
// Returns false otherwise.
static bool
_CheckShaderLocator(
    const HdDataSourceLocatorSet& dirtyLocators,
    const TfToken& renderContext,
    const TfToken& shaderName)
{
    return dirtyLocators.Contains({
        HdMaterialSchema::GetSchemaToken(), 
        renderContext,
        HdMaterialNetworkSchemaTokens->nodes,
        shaderName});
}

// Test dirty notices generated by UsdImaging's Material Adapter
// in different circumstances
static void
TestMaterialAdapter(
    const std::string& usdaFile)
{
    UsdStageRefPtr stage = UsdStage::Open(usdaFile);

    // Create the UsdImaging scene index graph.
    UsdImagingCreateSceneIndicesInfo info;
    info.stage = stage;
    const UsdImagingSceneIndices sceneIndices =
        UsdImagingCreateSceneIndices(info);
    sceneIndices.stageSceneIndex->SetTime(UsdTimeCode(0));

    DirtyNoticeListener dirtyNoticeListener;
    sceneIndices.stageSceneIndex->AddObserver(
        HdSceneIndexObserverPtr(&dirtyNoticeListener));

    const SdfPath materialPath("/Model/Looks/Material");

    // Change the value of a Shader within several NodeGraphs
    // The dirty locators should correctly target the Shader within the
    // NodeGraphs
    const SdfPath sharedColorInputRGBPath(
        "/Model/Looks/Material/Group/InnerGroup/SharedColor.inputs:inputRGB");
    const UsdAttribute inputRGB = stage->GetAttributeAtPath(sharedColorInputRGBPath);
    TF_VERIFY(inputRGB);
    inputRGB.Set(GfVec3f(1.0, 0.0, 0.0));
    sceneIndices.stageSceneIndex->ApplyPendingUpdates();

    {
        const DirtyNoticeListener::DirtiedPrimEntries& dirtyEntries = 
            dirtyNoticeListener.GetDirtied();
        // Verify that /Model/Looks/Material is the prim being dirtied
        TF_VERIFY(dirtyEntries.size() == 1);
        TF_VERIFY(dirtyEntries[0].primPath == materialPath);
        const HdDataSourceLocatorSet& dirtyLocators = 
            dirtyEntries[0].dirtyLocators;

        // Verify that the following locators are dirtied:
        // - material/_all/nodes/Group/InnerGroup/SharedColor
        // - material/ri/nodes/Group/InnerGroup/SharedColor
        // - material/ri/terminals/surface
        TF_VERIFY(std::distance(dirtyLocators.begin(), dirtyLocators.end()) == 3);
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            HdMaterialSchemaTokens->all,
            _tokens->SharedColor));
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            _tokens->renderContext,
            _tokens->SharedColor));
        TF_VERIFY(_CheckSurfaceTerminal(dirtyLocators));

        dirtyNoticeListener.ResetEntries();
    }

    // Change the value of an attribute of a NodeGraph. Verify that all Shader
    // prims connected to that attribute are dirtied
    const SdfPath mixerPath("/Model/Looks/Material/Group.inputs:mixer");
    const UsdAttribute mixer = stage->GetAttributeAtPath(mixerPath);
    TF_VERIFY(mixer);
    mixer.Set(0.1f);
    sceneIndices.stageSceneIndex->ApplyPendingUpdates();
    {
        const DirtyNoticeListener::DirtiedPrimEntries& dirtyEntries = 
            dirtyNoticeListener.GetDirtied();
        // Verify that /Model/Looks/Material is the prim being dirtied
        TF_VERIFY(dirtyEntries.size() == 1);
        TF_VERIFY(dirtyEntries[0].primPath == materialPath);
        const HdDataSourceLocatorSet& dirtyLocators = 
            dirtyEntries[0].dirtyLocators;

        // Verify that the following locators are dirtied:
        // - material/_all/nodes/Group/InnerGroup/AnotherMixColor
        // - material/ri/nodes/Group/InnerGroup/AnotherMixColor
        // - material/_all/nodes/Group/InnerGroup/MixColor
        // - material/ri/nodes/Group/InnerGroup/MixColor
        // - material/ri/terminals/surface
        TF_VERIFY(std::distance(dirtyLocators.begin(), dirtyLocators.end()) == 5);
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            HdMaterialSchemaTokens->all,
            _tokens->MixColor));
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            _tokens->renderContext,
            _tokens->MixColor));
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            HdMaterialSchemaTokens->all,
            _tokens->AnotherMixColor));
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            _tokens->renderContext,
            _tokens->AnotherMixColor));
        TF_VERIFY(_CheckSurfaceTerminal(dirtyLocators));

        dirtyNoticeListener.ResetEntries();
    }

    // Change the value of an attribute of a Shader owned by a Material
    const SdfPath floatValuePath(
        "/Model/Looks/Material/SharedFloat.inputs:FloatValue");
    const UsdAttribute floatValue = stage->GetAttributeAtPath(floatValuePath);
    TF_VERIFY(floatValue);
    floatValue.Set(0.2f);
    sceneIndices.stageSceneIndex->ApplyPendingUpdates();
    {
        const DirtyNoticeListener::DirtiedPrimEntries& dirtyEntries = 
            dirtyNoticeListener.GetDirtied();
        // Verify that /Model/Looks/Material is the prim being dirtied
        TF_VERIFY(dirtyEntries.size() == 1);
        TF_VERIFY(dirtyEntries[0].primPath == materialPath);
        const HdDataSourceLocatorSet& dirtyLocators = 
            dirtyEntries[0].dirtyLocators;

        // Verify that the following locators are dirtied:
        // - material/_all/nodes/SharedFloat
        // - material/ri/nodes/SharedFloat
        // - material/ri/terminals/surface
        TF_VERIFY(std::distance(dirtyLocators.begin(), dirtyLocators.end()) == 3);
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            HdMaterialSchemaTokens->all,
            _tokens->SharedFloat));
        TF_VERIFY(_CheckShaderLocator(dirtyLocators,
            _tokens->renderContext,
            _tokens->SharedFloat));
        TF_VERIFY(_CheckSurfaceTerminal(dirtyLocators));

        dirtyNoticeListener.ResetEntries();
    }
}

int
main(int argc, char* argv[])
{
    const auto usage = [&]() {
        std::cerr << "Usage: " << argv[0]
                  << " -stage <usda_file>\n";
    };

    if (argc < 3
        || std::string(argv[1]) != "-stage") {
        usage();
        return EXIT_FAILURE;
    
    }

    const std::string stageFile = "model.usda";

    TfErrorMark mark;

    TestMaterialAdapter(stageFile);

    TF_VERIFY(mark.IsClean());

    return EXIT_SUCCESS;
}