bool
Usd_ClipSet::BuildSpline(const SdfPath& path, TsSpline* result) const
{
    if (!manifestClip->HasAuthoredSpline(path)) {
        return false;
    }

    // Get the spline's type
    TfToken typeName;
    if (!manifestClip->HasField(path, SdfFieldKeys->TypeName, &typeName)) {
        return false;
    }
    const TfType valueType = Ts_GetTypeFromTypeName(typeName);

    // Get splines from clips to concatenate. We need to ensure that each
    // clip's built spline has knots at a external times shared by its adjacent
    // spline neighbors, if applicable.
    //
    // Note that we also track a pending start knot that gets completed into
    // a full spline when we encounter a clip with an authored spline or get
    // to the end of all clips. This enables us to "fill in the gaps" for
    // clips that don't have authored splines.
    std::vector<TsSpline> splines;
    TsKnot startKnot(valueType);
    bool hasPendingKnot = false;
    bool holdPreExtrap = false;
    for (const Usd_ClipRefPtr& clip : valueClips) {
        TsSpline spline;
        if (_ClipContainsAuthoredValueForAttribute(clip, path)
            && clip->BuildSpline(path, &spline))
        {
            if (hasPendingKnot) {
                // Compute the ending knot for the pending spline. Note that
                // extrapolations default to held.
                TsSpline pendingSpline(valueType);
                TsKnot endKnot(valueType);
                endKnot.SetTime(clip->startTime);
                if (startKnot.GetNextInterpolation() == TsInterpLinear) {
                    VtValue value;
                    if (spline.Eval(clip->startTime, &value)) {
                        endKnot.SetPreValue(value);
                    } else {
                        startKnot.SetNextInterpolation(TsInterpHeld);
                    }
                } else if (startKnot.GetNextInterpolation()
                           == TsInterpValueBlock && splines.empty())
                {
                    pendingSpline.SetPreExtrapolation(TsExtrapValueBlock);
                }

                pendingSpline.SetKnots({startKnot, endKnot});
                splines.push_back(pendingSpline);
                hasPendingKnot = false;
            }

            splines.push_back(spline);
            continue;
        }

        if (hasPendingKnot) {
            continue;
        }

        // Write the starting knot for the pending spline
        startKnot = TsKnot(valueType);
        startKnot.SetTime(clip->authoredStartTime);

        VtValue defaultValue;
        if (Usd_HasDefault(manifestClip, path, &defaultValue)
            == Usd_DefaultValueResult::Found)
        {
            // Build held spline with the manifest clip default value
            startKnot.SetValue(defaultValue);
            hasPendingKnot = true;
        } else if (!interpolateMissingClipValues) {
            // Build value block spline
            startKnot.SetNextInterpolation(TsInterpValueBlock);
            hasPendingKnot = true;
        } else if (interpolateMissingClipValues) {
            if (splines.empty()) {
                holdPreExtrap = true;
            } else {
                // Build a spline consisting entirely of one linear extrap.
                // The value of this spline's starting knot is the last
                // spline's last knot's preValue. If that preValue doesn't
                // exist, the pending spline should have a value block.
                VtValue value;
                if (splines.back().EvalPreValue(clip->startTime, &value)) {
                    startKnot.SetValue(value);
                    startKnot.SetNextInterpolation(TsInterpLinear);
                } else {
                    startKnot.SetNextInterpolation(TsInterpValueBlock);
                }
                hasPendingKnot = true;
            }
        }
    }

    if (hasPendingKnot) {
        TsSpline spline(valueType);
        spline.SetKnot(startKnot);
        if (startKnot.GetNextInterpolation() == TsInterpValueBlock) {
            spline.SetPostExtrapolation(TsExtrapValueBlock);

            if (splines.empty()) {
                spline.SetPreExtrapolation(TsExtrapValueBlock);
            }
        }
        splines.push_back(spline);
    }

    if (!splines.empty() && holdPreExtrap) {
        splines.front().SetPreExtrapolation(TsExtrapHeld);
    }

    *result = TsSpline::Concatenate(splines);
    return true;
}

size_t
Usd_ClipSet::_FindClipIndexForTime(double time) const
{
    size_t clipIndex = 0;

    // If there was only one clip, it must be active over all time so
    // we don't need to search any further.
    if (valueClips.size() > 1) {
        // Find the first clip whose start time is greater than the given
        // time.
        auto it = std::upper_bound(
            valueClips.begin(), valueClips.end(), time,
            [](double time, const Usd_ClipRefPtr& clip) {
                return time < clip->startTime;
            });

        // The upper bound should never be the first clip. Since its
        // startTime is set to -inf, it should never be greater than any
        // time that is given.
        if (TF_VERIFY(it != valueClips.begin())) {
            // The clip before the upper bound must have time in its
            // [startTime, endTime) range. This is true even if
            // it points to valueClips.end(); if this were the case,
            // then the given time is greater than the last clip's
            // startTime, but the last clip is active until +inf so
            // time must fall into its range.
            clipIndex = std::distance(valueClips.begin(), it) - 1;
        }
    }

    if (!TF_VERIFY(
            clipIndex < valueClips.size()
            // A clip is active in the interval [startTime, endTime) except
            // for the last clip which is active from [startTime, endTime].
            && time >= valueClips[clipIndex]->startTime 
            && (clipIndex == valueClips.size() - 1 ?
                    time <= valueClips[clipIndex]->endTime :
                    time < valueClips[clipIndex]->endTime))) {
        return 0;
    }

    return clipIndex;
}

